// Package generate turns discovered root modules into an Atlantis repo
// configuration (version 3) and renders it as deterministic YAML.
package generate

import (
	"bytes"
	"fmt"
	"path"
	"path/filepath"
	"sort"
	"strings"
	"text/template"

	"github.com/pmezard/go-difflib/difflib"
	"go.yaml.in/yaml/v3"

	"github.com/moveeeax/atlantis-config-gen/internal/discover"
)

// DefaultNameTemplate names a project after its directory base plus environment,
// e.g. "api" or "api-staging".
const DefaultNameTemplate = "{{.Base}}{{if .Env}}-{{.Env}}{{end}}"

// Options tunes the generated configuration.
type Options struct {
	Workflow     string // attached to every project when non-empty
	NameTemplate string // Go template evaluated per project
	Automerge    bool
	Parallel     bool // sets parallel_plan and parallel_apply
}

// Config is the subset of the Atlantis repo config we emit.
type Config struct {
	Version       int       `yaml:"version"`
	Automerge     bool      `yaml:"automerge,omitempty"`
	ParallelPlan  bool      `yaml:"parallel_plan,omitempty"`
	ParallelApply bool      `yaml:"parallel_apply,omitempty"`
	Projects      []Project `yaml:"projects"`
}

// Project is one Atlantis project entry.
type Project struct {
	Name              string   `yaml:"name"`
	Dir               string   `yaml:"dir"`
	Workspace         string   `yaml:"workspace,omitempty"`
	Workflow          string   `yaml:"workflow,omitempty"`
	Autoplan          Autoplan `yaml:"autoplan"`
	ApplyRequirements []string `yaml:"apply_requirements,omitempty"`
}

// Autoplan holds the autoplan trigger for a project.
type Autoplan struct {
	WhenModified []string `yaml:"when_modified"`
	Enabled      bool     `yaml:"enabled"`
}

type nameCtx struct {
	Dir  string // "envs/prod"
	Base string // "prod"
	Path string // "envs-prod"
	Env  string // "" or the environment name
}

// Build converts discovered roots into a Config. Projects and their trigger
// lists are fully sorted so repeated runs on the same tree are byte-identical.
func Build(roots []discover.RootModule, opt Options) (*Config, error) {
	if opt.NameTemplate == "" {
		opt.NameTemplate = DefaultNameTemplate
	}
	tmpl, err := template.New("name").Parse(opt.NameTemplate)
	if err != nil {
		return nil, fmt.Errorf("parse name-template: %w", err)
	}

	cfg := &Config{
		Version:       3,
		Automerge:     opt.Automerge,
		ParallelPlan:  opt.Parallel,
		ParallelApply: opt.Parallel,
	}

	for _, rm := range roots {
		triggers := whenModified(rm)
		envs := rm.Environments
		if len(envs) == 0 {
			envs = []string{""} // one project on the default workspace
		}
		for _, env := range envs {
			p, err := project(rm, env, triggers, opt, tmpl)
			if err != nil {
				return nil, err
			}
			cfg.Projects = append(cfg.Projects, p)
		}
	}

	sort.Slice(cfg.Projects, func(i, j int) bool {
		if cfg.Projects[i].Dir != cfg.Projects[j].Dir {
			return cfg.Projects[i].Dir < cfg.Projects[j].Dir
		}
		return cfg.Projects[i].Workspace < cfg.Projects[j].Workspace
	})
	return cfg, nil
}

func project(rm discover.RootModule, env string, triggers []string, opt Options, tmpl *template.Template) (Project, error) {
	base := path.Base(rm.Dir)
	if rm.Dir == "." {
		base = "root"
	}
	ctx := nameCtx{
		Dir:  rm.Dir,
		Base: base,
		Path: strings.ReplaceAll(rm.Dir, "/", "-"),
		Env:  env,
	}
	var nb bytes.Buffer
	if err := tmpl.Execute(&nb, ctx); err != nil {
		return Project{}, fmt.Errorf("render name for %q: %w", rm.Dir, err)
	}
	name := strings.Trim(nb.String(), "-/ ")
	if name == "" {
		name = ctx.Path
	}

	workspace := env
	if workspace == "" {
		workspace = "default"
	}

	return Project{
		Name:              name,
		Dir:               rm.Dir,
		Workspace:         workspace,
		Workflow:          opt.Workflow,
		Autoplan:          Autoplan{WhenModified: triggers, Enabled: true},
		ApplyRequirements: []string{"approved"},
	}, nil
}

// whenModified builds the autoplan trigger list for a root: its own Terraform
// and tfvars files, plus every transitively-used local module's Terraform files,
// each expressed relative to the project directory (as Atlantis expects).
func whenModified(rm discover.RootModule) []string {
	set := map[string]bool{
		"*.tf":     true,
		"*.tfvars": true,
		"*.hcl":    true, // .terraform.lock.hcl and friends
	}
	for _, dep := range rm.ModuleDeps {
		rel, err := filepath.Rel(rm.Dir, dep)
		if err != nil {
			rel = dep
		}
		set[path.Join(filepath.ToSlash(rel), "*.tf")] = true
	}
	out := make([]string, 0, len(set))
	for k := range set {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// Render encodes cfg as YAML with a leading provenance comment.
func Render(cfg *Config) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("# Generated by atlantis-config-gen. Re-run to update; do not edit by hand.\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(cfg); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// UnifiedDiff returns a unified diff from existing to generated, or "" when they
// are identical.
func UnifiedDiff(existing, generated, name string) string {
	if existing == generated {
		return ""
	}
	out, _ := difflib.GetUnifiedDiffString(difflib.UnifiedDiff{
		A:        difflib.SplitLines(existing),
		B:        difflib.SplitLines(generated),
		FromFile: name + " (current)",
		ToFile:   name + " (generated)",
		Context:  3,
	})
	return out
}
